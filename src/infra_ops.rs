use std::ffi::OsString;
use std::path::PathBuf;
use std::process::Command;

use anyhow::{Context, Result, ensure};
use clap::Subcommand;

use crate::client::host_url;
use crate::infra;
use crate::process;
use crate::source::{Kind, Sources};

#[derive(Subcommand)]
pub enum CommandKind {
    /// Evaluate the infrastructure flake and build its declared checks.
    Check {
        #[command(flatten)]
        source: SourceArgs,
    },
    /// Build one declared host's system closure locally.
    Build {
        /// Host name from modules/systems.nix.
        host: String,
        /// Build a nix-darwin configuration instead of a NixOS configuration.
        #[arg(long)]
        darwin: bool,
        #[command(flatten)]
        source: SourceArgs,
    },
    /// Build the Atlantis configuration generated by the infrastructure flake.
    AtlantisConfig {
        #[command(flatten)]
        source: SourceArgs,
    },
    /// Run a Colmena command from a complete local infrastructure checkout.
    Colmena {
        /// Local checkout containing flake.nix, flake.lock, and devenv.nix.
        #[arg(long, required = true)]
        checkout: PathBuf,
        /// Arguments passed to Colmena after `--`.
        #[arg(last = true, required = true, num_args = 1.., allow_hyphen_values = true)]
        args: Vec<OsString>,
    },
}

#[derive(clap::Args)]
pub struct SourceArgs {
    /// Use a local infrastructure checkout, including uncommitted changes.
    #[arg(long, env = "COLLAR_INFRASTRUCTURE")]
    checkout: Option<PathBuf>,
    /// Read the last verified canonical source snapshot and keep Nix offline.
    #[arg(long = "offline-source")]
    offline_source: bool,
}

pub fn run(command: CommandKind, sources: &Sources<'_>) -> Result<()> {
    if let CommandKind::Colmena { checkout, args } = &command {
        let checkout =
            std::fs::canonicalize(checkout).context("resolve infrastructure checkout")?;
        for file in ["flake.nix", "flake.lock", "devenv.nix"] {
            ensure!(checkout.join(file).is_file(), "checkout has no {file}");
        }
        let mut devenv = Command::new("devenv");
        devenv
            .current_dir(checkout)
            .args(["shell", "--", "colmena"])
            .args(args);
        return process::run(&mut devenv);
    }
    let args = match &command {
        CommandKind::Check { source }
        | CommandKind::Build { source, .. }
        | CommandKind::AtlantisConfig { source } => source,
        CommandKind::Colmena { .. } => unreachable!(),
    };
    let source = sources.load(
        Kind::Infrastructure,
        args.checkout.clone(),
        args.offline_source,
    )?;
    let (flake, reference) = if let Some(checkout) = args.checkout.clone() {
        let flake = std::fs::canonicalize(checkout).context("resolve infrastructure checkout")?;
        (Some(flake.clone()), flake.display().to_string())
    } else {
        let revision = source
            .revision
            .as_deref()
            .context("canonical infrastructure snapshot has no revision")?;
        let origin = host_url(sources.host.unwrap_or(sources.config.host()))?;
        (
            None,
            format!("git+{origin}ScottyLabs/infrastructure?rev={revision}"),
        )
    };
    if let Some(flake) = &flake {
        ensure!(
            flake.join("flake.nix").is_file(),
            "checkout has no flake.nix"
        );
        ensure!(
            flake.join("flake.lock").is_file(),
            "checkout has no flake.lock"
        );
    }

    let mut nix = Command::new("nix");
    if let Some(flake) = &flake {
        nix.current_dir(flake);
    }
    if args.offline_source {
        nix.arg("--offline");
    }
    match command {
        CommandKind::Check { .. } => {
            nix.args(["flake", "check"]).arg(&reference);
        }
        CommandKind::Build { host, darwin, .. } => {
            let hosts = infra::hosts(&source.directory)?;
            ensure!(
                hosts.iter().any(|entry| entry.name == host),
                "unknown infrastructure host {host}"
            );
            let family = if darwin { "darwin" } else { "nixos" };
            let output =
                format!("{reference}#{family}Configurations.{host}.config.system.build.toplevel");
            nix.args(["build"]).arg(output).arg("--no-link");
        }
        CommandKind::AtlantisConfig { .. } => {
            nix.args(["build"])
                .arg(format!("{reference}#atlantis-yaml"))
                .arg("--no-link");
        }
        CommandKind::Colmena { .. } => unreachable!(),
    }
    process::run(&mut nix).with_context(|| format!("{}; Nix input {reference}", source.describe()))
}
